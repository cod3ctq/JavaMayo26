--CREAR UNA TABLA
CREATE TABLE CLIENTES(
CLIENTE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(100),
AP_P VARCHAR2(100),
AP_M VARCHAR2(100),
DIRECCION VARCHAR2(100),
TELEFONO CHAR(10),
INE CHAR(18),
RFC CHAR(13),
FECHA_NAC DATE,
STATUS CHAR(1) --0 1
--FECHA_REGISTRO DATE,
--FECHA_ACTUALIZACION DATE
);

