/*CONSTRAINT CHECK - RESTABLECER LOS VALORES POSIBLES A INSERTAR/ACTUALIZAR EN UNA FILA */
ALTER TABLE TARJETAS ADD CONSTRAINT CHK_TARJETAS_STATUS
CHECK(STATUS IN ('ACTIVO', 'BLOQUEADO', 'DESACTIVADO'));

ALTER TABLE CUENTAS ADD CONSTRAINT CHK_CUENTAS_STATUS
CHECK(STATUS IN ('0', '1'));

ALTER TABLE EMPLEADOS ADD CONSTRAINT CHK_EMPLEADOS_STATUS
CHECK(STATUS IN ('ACTIVO', 'INACTIVO', 'SUSPENDIDO'));

ALTER TABLE RECIBOS ADD CONSTRAINT CHK_RECIBOS_STATUS
