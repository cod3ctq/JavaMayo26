CREATE OR REPLACE PROCEDURE PAGAR_RECIBO_TARJETA(
    P_NUM_TARJETA IN TARJETAS.NUM_TARJETA%TYPE,
    P_CONVENIO    IN SERVICIOS.CONVENIO%TYPE,
    P_REFERENCIA  IN RECIBOS.REFERENCIA%TYPE
)
AS --DLECARA VARIABLES LOCALES (SOLO EXISTEN DENTRO DEL START PROCEDURE )
    V_CUENTA_ID  CUENTAS.CUENTA_ID%TYPE;
    V_SALDO      CUENTAS.SALDO%TYPE;
    V_SERVICIO_ID SERVICIOS.SERVICIO_ID%TYPE;
    V_RECIBO_ID  RECIBOS.RECIBO_ID%TYPE;
    V_MONTO      RECIBOS.MONTO%TYPE;
    V_STATUS     RECIBOS.STATUS%TYPE;
BEGIN --INDICA EL INICIO DE LA LOGICA DEL START PROCEDURE

    SELECT C.CUENTA_ID, C.SALDO
    INTO V_CUENTA_ID, V_SALDO
    FROM TARJETAS T
    INNER JOIN CUENTAS C ON T.CUENTA_ID = C.CUENTA_ID
    WHERE T.NUM_TARJETA = P_NUM_TARJETA
    AND T.STATUS = 'ACTIVO'
    AND C.STATUS = '1';

    SELECT SERVICIO_ID
    INTO V_SERVICIO_ID
    FROM SERVICIOS
    WHERE CONVENIO = P_CONVENIO;

    SELECT RECIBO_ID, MONTO, STATUS
    INTO V_RECIBO_ID, V_MONTO, V_STATUS
    FROM RECIBOS
    WHERE SERVICIO_ID = V_SERVICIO_ID
    AND REFERENCIA = P_REFERENCIA;

-- -2001 HASTA -20999 (RANGO DE NUMEROS PARA LANZAR MENSAJES PERSONALIZADOS EN ORACLE
-- Si el recibo ya esta pagado
    IF V_STATUS = '1' THEN
    RAISE_APPLICATION_ERROR(-20001, 'El recibo ya fue pagado');
    END IF;

-- Si el status no es pendiente
    IF V_STATUS <> '0' THEN
    RAISE_APPLICATION_ERROR(-20002, 'El recibo tiene un status inválido');
    END IF;

-- Validar saldo suficiente
    IF V_SALDO < V_MONTO THEN
    RAISE_APPLICATION_ERROR(-20003, 'Saldo insuficiente para realizar el pago');
    END IF;

-- Descontar saldo de la cuenta
    UPDATE CUENTAS
    SET SALDO = SALDO - V_MONTO
    WHERE CUENTA_ID = V_CUENTA_ID;

-- Actualizar recibo a pagado
    UPDATE RECIBOS
    SET STATUS = '1'
    WHERE REFERENCIA = P_REFERENCIA;

    COMMIT;--MANUAL

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20004, 'No se encontró tarjeta, cuenta, convenio o recibo asociado');

    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
