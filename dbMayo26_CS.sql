CLIENTE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2 (100),
AP_P VARCHAR2 (100),
AP_M VARCHAR2 (100),
DIRECCION VARCHAR2 (100),
TELEFONO CHAR (10),
INE CHAR (18),
RFC CHAR (13),
FECHA_NAC DATE,
STATUS CHAR(1), -- 0 1
--FECHA_REGISTRO DATE,
--FECHA_ACTUALIZACION DATE
);

--Ver estructura de la tabla
DESCRIBE CLIENTES;

/*Modificar la estructura de una tabla: eliminar columnas */
ALTER TABLE CLIENTES DROP COLUMN FECHA_REGISTRO;
ALTER TABLE CLIENTES DROP COLUMN FECHA_ACTUALIZACION;

/*MODIFICAR LA ESTRUCUTRA DE UNA TABLA: AGREGAR COLUMNAS*/
ALTER TABLE CLIENTES ADD CORREO VARCHAR2(100);


/*CONSTRAINT UNIQUE, CHECK
DEFINIR QUE NO SE REPITAN DATOS EN ALGUNA COLUMNA EN PARTICULAR*/
ALTER TABLE CLIENTES ADD CONSTRAINT UQ_CLIENTES_INE_RFC
UNIQUE(INE, RFC); -- LA COMBINACION DE LOS 2 DATOS, DEBE SER UNICA

ALTER TABLE CUENTAS ADD CONSTRAINT UQ_CUENTAS_NUM_CUENTA
UNIQUE(NUM_CUENTA);

ALTER TABLE CUENTAS ADD CONSTRAINT UQ_CUENTAS_CLABE
UNIQUE(CLABE);
ALTER TABLE TARJETAS ADD CONSTRAINT UQ_NUM_TARJETA
UNIQUE (NUM_TARJETA);
ALTER TABLE EMPLEADOS ADD CONSTRAINT UQ_EMPLEADOS_TEL
UNIQUE(TEL);
