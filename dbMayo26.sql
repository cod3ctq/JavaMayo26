-- CREAR TABLA
CREATE TABLE CLIENTES(
CLIENTE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(100),
AP_P VARCHAR2(100),
AP_M VARCHAR2(100),
DIRECCION VARCHAR2(100),
TELEFONO CHAR(10),
INE CHAR(18),
RFC CHAR(13),
FECHA_NAC DATE,
STATUS CHAR(1) -- 0 1
--FECHA_REGISTRO DATE,
--FECHA_ACTUALIZACION DATE
);

CREATE TABLE TARJETAS(
TARJETA_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
CUENTA_ID NUMBER,
TIPO_TARJETA_ID NUMBER,
NUM_TARJETA CHAR(16),
NIP CHAR(4), -- UNIQUE
FECHA_VEN DATE,
STATUS VARCHAR2(15)   -- CHECK(ACTIVA, BLOQUEADA, DESACTIVADA)
);

CREATE TABLE CUENTAS(
CUENTA_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
CLIENTE_ID NUMBER,
TIPO_CUENTA_ID NUMBER,
NUM_CUENTA VARCHAR2(10),
CLABE CHAR(18),
SALDO NUMBER(8,2),    ---500000.00
FECHA_AP DATE,
STATUS CHAR(1) -- CHECK(0,1)
);


CREATE TABLE MOVIMIENTOS(
MOV_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
CUENTA_ID NUMBER,
TIPO VARCHAR2(100),
FECHA_OP DATE,
MONTO NUMBER(8,2)  --- 999999.99
);

CREATE TABLE PRESTAMOS(
PRESTAMO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
TIPO_ID NUMBER,
CLIENTE_ID NUMBER,
FECHA DATE,
MONTO NUMBER(8,2),
FECHA_FIN DATE,
RESTANTE NUMBER(8,2)
);

CREATE TABLE EMPLEADOS(
EMPLEADO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
ROL_ID NUMBER,
NOMBRE VARCHAR2(100),
AP_P VARCHAR2(100),
AP_M VARCHAR2(100),
FECHA_IN DATE,
CORREO VARCHAR2(100),
TEL CHAR(10),
STATUS VARCHAR2(50) -- ACTIVO, INACTIVO, SUSPENDIDO
);

CREATE TABLE ABONOS(
ABONO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
PRESTAMO_ID NUMBER,
FECHA DATE,
MONTO NUMBER(8,2),
MEDIO_PAGO NUMBER
);

CREATE TABLE ROLES(
ROL_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100),
SUELDO NUMBER(8,2)
);

CREATE TABLE TIPO_TARJETA(
TIPO_T_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100)
);

CREATE TABLE TIPO_CUENTA(
TIPO_CUENTA_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100),
SALDO_MIN NUMBER(8,2),
SALDO_MAX NUMBER(8,2)
);

CREATE TABLE TIPO_PRESTAMO(
TIPO_PRESTAMO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100),
INTERES NUMBER,
PLAZO NUMBER
);

CREATE TABLE MEDIOS_PAGO(
MEDIO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100)
);


CREATE TABLE SERVICIOS(
SERVICIO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
CONVENIO VARCHAR2(10),
DESCRIPCION VARCHAR2(30)
);

CREATE TABLE RECIBOS(
RECIBO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
SERVICIO_ID NUMBER,
REFERENCIA VARCHAR2(20),
FECHA_INICIO DATE,
FECHA_FIN DATE,
MONTO NUMBER,
STATUS CHAR(1) -- 0 , 1
);


