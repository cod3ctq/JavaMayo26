-- CREACIÓN DE TABLAS
CREATE TABLE CLIENTES ( -- Sintaxis para la creación de una tabla
-- Creamos la primera columna (CLIENTE_ID) y tipo de dato "NUMBER" (Equivalente a "int" en Java)
CLIENTE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, -- SINTAXIS PARA CREAR LLAVE PRIMARIA
-- Creamos segunda columna (NOMBRE) y tipo de dato "VARCHAR2" (Equivalente a String en Java)
NOMBRE VARCHAR2(100), -- Longitud de hasta 100 caracteres
AP_P VARCHAR2(100),
AP_M VARCHAR2(100),
DIRECCION VARCHAR2(100),
TELEFONO CHAR(10), -- Tipo de dato "CHAR" que es texto pero con longitud fija, tiene que tener 10 posiciones
INE CHAR(18),
RFC CHAR(13),
FECHA_NAC DATE,
STATUS CHAR(1) -- 0 o 1 para el status, en esta versión de Oracle no existe "boolean"
);

CREATE TABLE CUENTAS(
CUENTA_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
CLIENTE_ID NUMBER,
TIPO_CUENTA_ID NUMBER,
NUM_CUENTA VARCHAR2(10),
CLABE CHAR(18),
SALDO NUMBER(8,2), -- 500000.00 / 8 CIFRAS MAXIMO, DE LAS CUALES 2 SERÁN DECIMALES
FECHA_AP DATE,
STATUS CHAR(1)
);

CREATE TABLE TARJETAS(
TARJETA_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
CUENTA_ID NUMBER,
TIPO_TARJETA_ID NUMBER,
NUM_TARJETA CHAR(16),
NIP CHAR(4), -- UNIQUE
FECHA_VEN DATE,
STATUS VARCHAR2(15) -- CHECK(ACTIVA, BLOQUEADA, DESACTIVADA)
);

CREATE TABLE MOVIMIENTOS(
MOV_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
CUENTA_ID NUMBER,
TIPO VARCHAR2(100),
FECHA_OP DATE,
MONTO NUMBER(8,2)  --- 999999.99
);

CREATE TABLE PRESTAMOS(
PRESTAMO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
TIPO_ID NUMBER,
CLIENTE_ID NUMBER,
FECHA DATE,
MONTO NUMBER(8,2),
FECHA_FIN DATE,
RESTANTE NUMBER(8,2)
);

CREATE TABLE EMPLEADOS(
EMPLEADO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
ROL_ID NUMBER,
NOMBRE VARCHAR2(100),
AP_P VARCHAR2(100),
AP_M VARCHAR2(100),
FECHA_IN DATE,
CORREO VARCHAR2(100),
TEL CHAR(10),
STATUS VARCHAR2(50) -- ACTIVO, INACTIVO, SUSPENDIDO
);

CREATE TABLE ABONOS(
ABONO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
PRESTAMO_ID NUMBER,
FECHA DATE,
MONTO NUMBER(8,2),
MEDIO_PAGO NUMBER
);

CREATE TABLE ROLES(
ROL_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100),
SUELDO NUMBER(8,2)
);

CREATE TABLE TIPO_TARJETA(
TIPO_T_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100)
);

CREATE TABLE TIPO_CUENTA(
TIPO_CUENTA_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100),
SALDO_MIN NUMBER(8,2),
SALDO_MAX NUMBER(8,2)
);

CREATE TABLE TIPO_PRESTAMO(
TIPO_PRESTAMO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100),
INTERES NUMBER,
PLAZO NUMBER
);

CREATE TABLE MEDIOS_PAGO(
MEDIO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
DESCRIPCION VARCHAR2(100)
);

CREATE TABLE SERVICIOS(
SERVICIO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
CONVENIO VARCHAR2(10),
DESCRIPCION VARCHAR2(30)
);

CREATE TABLE RECIBOS(
RECIBO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
SERVICIO_ID NUMBER,
REFERENCIA VARCHAR2(20),
FECHA_INICIO DATE,
FECHA_FIN DATE,
MONTO NUMBER,
STATUS CHAR(1) -- 0 , 1
);

-- CREACIÓN DE CONSTRAINT LLAVE FORÁNEA
-- ES LA LLAVE QUE SE RELACIONARÁ A LA LLAVE PRIMARIA DE OTRA TABLA CON LA CUÁL SE VAN A RELACIONAR LOS REGISTROS
ALTER TABLE CUENTAS -- INDICAMOS QUE VAMOS A MODIFICAR LA TABLA "CUENTAS"
ADD CONSTRAINT FK_CUENTAS_CLIENTE_ID -- AGREGAMOS UNA RESTRICCIÓN Y EL NOMBRE QUE LE ASIGNAMOS (FK = FOREIGN KEY)
FOREIGN KEY(CLIENTE_ID) -- COLUMNA QUE RECIBE LA REGLA, LA QUE SERÁ LA LLAVE FORNÁNEA
REFERENCES CLIENTES(CLIENTE_ID); -- A QUÉ COLUMNA Y DE QUÉ TABLA APUNTA LA LLAVE FORÁNEA

ALTER TABLE TARJETAS -- INDICAMOS QUE VAMOS A MODIFICAR LA TABLA "TARJETAS"
ADD CONSTRAINT FK_TARJETAS_CUENTA_ID -- AGREGAMOS UNA RESTRICCIÓN Y EL NOMBRE QUE LE ASIGNAMOS (FK = FOREIGN KEY)
FOREIGN KEY(CUENTA_ID) -- COLUMNA QUE RECIBE LA REGLA, LA QUE SERÁ LA LLAVE FORNÁNEA
REFERENCES CUENTAS(CUENTA_ID) -- A QUÉ COLUMNA Y DE QUÉ TABLA APUNTA LA LLAVE FORÁNEA

ALTER TABLE PRESTAMOS
ADD CONSTRAINT FK_PRESTAMOS_CLIENTE_ID
FOREIGN KEY(CLIENTE_ID)
REFERENCES CLIENTES(CLIENTE_ID);

ALTER TABLE MOVIMIENTOS
ADD CONSTRAINT FK_MOVIMIENTOS_CUENTA_ID
FOREIGN KEY(CUENTA_ID)
REFERENCES CUENTAS(CUENTA_ID);

ALTER TABLE EMPLEADOS
ADD CONSTRAINT FK_EMPLEADOS_ROL_ID
FOREIGN KEY(ROL_ID)
REFERENCES ROLES(ROL_ID);

ALTER TABLE CUENTAS
ADD CONSTRAINT FK_CUENTAS_TIPOCUENTA_ID
FOREIGN KEY(TIPO_CUENTA_ID)
REFERENCES TIPO_CUENTA(TIPO_CUENTA_ID);

ALTER TABLE ABONOS
ADD CONSTRAINT FK_ABONOS_PRESTAMO_ID
FOREIGN KEY(PRESTAMO_ID)  
REFERENCES PRESTAMOS(PRESTAMO_ID);

ALTER TABLE TARJETAS
ADD CONSTRAINT FK_TARJETAS_TIP_ID
FOREIGN KEY(TIPO_TARJETA_ID)
REFERENCES TIPO_TARJETA(TIPO_T_ID);

ALTER TABLE ABONOS
ADD CONSTRAINT FK_ABONOS_MEDIO_PAGO
FOREIGN KEY(MEDIO_PAGO) 
REFERENCES MEDIOS_PAGO(MEDIO_ID);

ALTER TABLE PRESTAMOS
ADD CONSTRAINT FK_PRESTAMOS_TIPO_ID
FOREIGN KEY(TIPO_ID)
REFERENCES TIPO_PRESTAMO(TIPO_PRESTAMO_ID);

ALTER TABLE RECIBOS
ADD CONSTRAINT FK_RECIBOS_SERVICIO_ID
FOREIGN KEY(SERVICIO_ID)
REFERENCES SERVICIOS(SERVICIO_ID);

-- CREACIÓN DE CONSTRAINT UNIQUE
-- DEFINIR QUE NO SE REPITAN DATOS EN ALGUNA COLUMNA EN PARTICULAR
ALTER TABLE CLIENTES -- MODIFICAMOS LA TABLA CLIENTES
ADD CONSTRAINT UQ_CLIENTES_INE_RFC -- AGREGAMOS EL CONSTRAINT Y LO NOMBRAMOS (UQ = UNIQUE)
UNIQUE(INE, RFC); -- LA COMBINACIÓN DE LOS 2 DATOS DEBE SER ÚNICA

ALTER TABLE CUENTAS -- MODIFICAMOS LA TABLA CUENTAS
ADD CONSTRAINT UQ_CUENTAS_NUM_CUENTA -- AGREGAMOS EL CONSTRAINT Y LO NOMBRAMOS
UNIQUE(NUM_CUENTA); -- NO SE PUEDE REPETIR EL DATO EN ESTA COLUMNA

ALTER TABLE CUENTAS -- MODIFICAMOS LA TABLA CLIENTES
ADD CONSTRAINT UQ_CUENTAS_CLABE -- AGREGAMOS EL CONSTRAINT Y LO NOMBRAMOS
UNIQUE(CLABE); -- NO SE PUEDE REPETIR EL DATO EN ESTA COLUMNA

ALTER TABLE TARJETAS
ADD CONSTRAINT UQ_TARJETAS_NUM_TARJETA
UNIQUE(NUM_TARJETA);

ALTER TABLE EMPLEADOS
ADD CONSTRAINT UQ_EMPLEADOS_TEL
UNIQUE(TEL);

ALTER TABLE EMPLEADOS
ADD CONSTRAINT UQ_EMPLEADOS_CORREO
UNIQUE(CORREO);

-- CREACIÓN DE CONSTRAINT CHECK
-- ESTABLECER LOS VALORES VÁLIDOS POSIBLES A INSERTAR/ACTUALIZAR EN UNA COLUMNA
ALTER TABLE TARJETAS -- INDICAMOS QUE VAMOS A MODIFICAR LA TABLA "TARJETAS"
ADD CONSTRAINT CHK_TARJETAS_STATUS -- AGREGAMOS EL CONSTRAINT Y LO NOMBRAMOS
CHECK(STATUS IN('ACTIVO', 'BLOQUEADO', 'DESACTIVADO')); -- INDICAMOS EN QUÉ COLUMNA Y LAS ÚNICAS POSIBLES OPCIONES EN ELLA

ALTER TABLE CUENTAS
ADD CONSTRAINT CHK_CUENTAS_STATUS
CHECK(STATUS IN('0', '1')); -- 0: INACTIVO, 1: ACTIVO

ALTER TABLE EMPLEADOS
ADD CONSTRAINT CHK_EMPLEADOS_STATUS
CHECK(STATUS IN('ACTIVO', 'INACTIVO', 'SUSPENDIDO'));

ALTER TABLE RECIBOS
ADD CONSTRAINT CHK_RECIBOS_STATUS
CHECK(STATUS IN('0', '1'));

ALTER TABLE MOVIMIENTOS
ADD CONSTRAINT CHK_MOVIMIENTOS_TIPO
CHECK(TIPO IN('DEPOSITO', 'RETIRO', 'TRANSFERENCIA', 'PAGO SERVICIOS'));

